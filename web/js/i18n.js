export function t(key, ...args) {
  const dict = I18N[currentLang] || I18N.de;
  let str = dict[key] || I18N.en[key] || I18N.de[key] || key;
  if (args.length) {
    args.forEach((val, i) => {
      str = str.replace(new RegExp(`\\{${i}\\}`, 'g'), val);
    });
  }
  return str;
}

